// Island endpoints and ledge coordinates are in world pixels.
export function map(name, theme, ground, platforms, enemies, hazards = [], extra = {}) {
  const width = ground.at(-1)[1];
  const coins = platforms.map(([x, y, w]) => [x + Math.round(w / 2), y - 16]);
  for (const [start, end] of ground) {
    if (end - start >= 160) coins.push([start + 43, 166], [end - 27, 166]);
  }
  return {
    name, theme, width, spawnX: 40, flagX: width - 42, ground, platforms, enemies, hazards, coins,
    trees: ground.flatMap(([start, end]) => [[start + 26, .55], [end - 30, .7]]),
    ...extra,
  };
}

